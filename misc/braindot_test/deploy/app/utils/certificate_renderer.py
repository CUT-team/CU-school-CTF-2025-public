class CustomSandbox(SandboxedEnvironment):
    def is_safe_callable(self, obj):
        # Разрешаем вызов globals() и locals()
        if obj in [globals, locals]:
            return True
        return super().is_safe_callable(obj)
    
env = CustomSandbox()

def read_file_lines(filename):
    try:
        with open(filename, 'r') as f:
            return f.readlines()
    except Exception as e:
        return ["Error"]
    
env.globals['read_file_lines'] = read_file_lines
env.globals['locals'] = locals

